"""DeepSeek API integration & prompt engine.

The cloud "brain" is only invoked for tickers that already cleared the local
hard-rule filter, which keeps credit usage and latency tiny. Everything the
model returns is normalised into an `AdvisorReport` so downstream code
(notifier, report writer) never has to parse prose.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional

import requests

log = logging.getLogger("alphaseek.ai")

SYSTEM_PROMPT = (
    "You are a disciplined US equities swing-trading analyst embedded in an "
    "automated screening system. You receive a *pre-filtered* technical setup "
    "and must judge whether it is tradable. Be skeptical: reject weak setups, "
    "and say so explicitly. Never invent fundamentals, news, or earnings dates "
    "you cannot support — instead flag them as unknowns to verify.\n\n"
    "Respond with STRICT JSON only (no markdown fences) using exactly these keys:\n"
    "{\n"
    '  "action": "BUY" | "WATCH" | "SKIP",\n'
    '  "confidence": <number 0-10, one decimal>,\n'
    '  "entry": <number, suggested entry price>,\n'
    '  "stop_loss": <number>,\n'
    '  "target": <number>,\n'
    '  "horizon_days": <integer, expected holding window>,\n'
    '  "rationale": "<2-4 sentences: why this setup works or fails>",\n'
    '  "risk_notes": "<1-2 sentences on what invalidates the thesis>",\n'
    '  "red_flags": ["<short string>", ...]\n'
    "}"
)

USER_PROMPT_TEMPLATE = """Evaluate this pre-filtered daily-bar setup.

Ticker: {ticker}
Last close: {price:.2f} (prev close {prev_close:.2f}, {change_pct:+.2f}%)
EMA{ema_fast_len}: {ema_fast:.2f} | EMA{ema_slow_len}: {ema_slow:.2f} (gap {ema_gap_pct:+.2f}%)
RSI({rsi_period}): {rsi:.1f}  (system sweet-spot {rsi_min:g}-{rsi_max:g})
Volume: {volume:,.0f} vs 20d avg {avg_volume:,.0f} = {volume_surge:.2f}x
ATR14: {atr:.2f} ({atr_pct:.2f}% of price)
20d avg dollar volume: ${avg_dollar_volume:,.0f}

Hard rules that already passed:
{reasons}

Rules of engagement:
- Only call BUY if the trend, momentum and volume evidence agree.
- Set stop_loss below a level that invalidates the setup (ATR-aware).
- Target must give at least 2:1 reward-to-risk, otherwise downgrade to WATCH.
- If information you would need (earnings date, news, sector context) is unknown, add a red flag instead of guessing.
"""


@dataclass
class AdvisorReport:
    ticker: str
    action: str
    confidence: float
    entry: float
    stop_loss: float
    target: float
    rationale: str
    horizon_days: Optional[int] = None
    risk_notes: str = ""
    red_flags: List[str] = field(default_factory=list)
    model: str = ""
    source: str = "deepseek"  # or "rule-based"
    error: str = ""

    @property
    def risk_reward(self) -> float:
        risk = self.entry - self.stop_loss
        if risk <= 0:
            return 0.0
        return (self.target - self.entry) / risk

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["risk_reward"] = round(self.risk_reward, 2)
        return data

    def render(self) -> str:
        lines = [
            "=" * 40,
            f"[{self.ticker} Signal Report]",
            f"Action: {self.action} (Confidence: {self.confidence:.1f}/10)",
            f"Current Price: ${self.entry:.2f}",
            f"Stop Loss: ${self.stop_loss:.2f} | Target: ${self.target:.2f} "
            f"(R:R {self.risk_reward:.1f}:1)",
            f"Core Rationale: {self.rationale}",
        ]
        if self.horizon_days:
            lines.append(f"Horizon: ~{self.horizon_days} trading days")
        if self.risk_notes:
            lines.append(f"Risk Notes: {self.risk_notes}")
        if self.red_flags:
            lines.append("Red Flags: " + "; ".join(self.red_flags))
        if self.source != "deepseek":
            lines.append(f"[note] Generated by {self.source} fallback ({self.model}).")
        lines.append("=" * 40)
        return "\n".join(lines)


class AIAdvisor:
    """Thin, dependency-light DeepSeek chat client with a rule-based fallback."""

    def __init__(self, settings) -> None:
        self.settings = settings
        cfg = settings.get("ai", {})
        self.model = str(cfg.get("model", "deepseek-chat"))
        self.base_url = str(cfg.get("base_url", "https://api.deepseek.com")).rstrip("/")
        self.temperature = float(cfg.get("temperature", 0.2))
        self.max_tokens = int(cfg.get("max_tokens", 1200))
        self.timeout = int(cfg.get("timeout_seconds", 90))
        self.dry_run = bool(cfg.get("dry_run", False))
        self.api_key = settings.api_key

    # -- public API -------------------------------------------------------
    @property
    def enabled(self) -> bool:
        return bool(self.api_key) and not self.dry_run

    def review(self, signal) -> AdvisorReport:
        """Return an advisor report for one passing signal."""
        if not self.enabled:
            reason = "dry-run mode" if self.dry_run else "no DEEPSEEK_API_KEY"
            log.info("[AI REVIEW] %s: DeepSeek disabled (%s), using rule-based plan.", signal.ticker, reason)
            return self._rule_based(signal, note=reason)

        try:
            payload = self._call(signal)
            report = self._parse(signal, payload)
            log.info(
                "[AI REVIEW] %s: %s conf=%.1f (%.1fs budget, model=%s)",
                signal.ticker,
                report.action,
                report.confidence,
                self.timeout,
                self.model,
            )
            return report
        except Exception as exc:  # network / quota / malformed JSON
            log.error("[AI REVIEW] %s: DeepSeek call failed: %s", signal.ticker, exc)
            return self._rule_based(signal, note=f"DeepSeek error: {exc}")

    # -- transport --------------------------------------------------------
    def _call(self, signal) -> Dict[str, Any]:
        cfg = self.settings.get("indicators", {})
        atr_pct = (signal.atr / signal.price * 100) if signal.price else 0.0
        user_prompt = USER_PROMPT_TEMPLATE.format(
            ticker=signal.ticker,
            price=signal.price,
            prev_close=signal.prev_close,
            change_pct=signal.change_pct,
            ema_fast_len=int(cfg.get("ema_fast", 20)),
            ema_slow_len=int(cfg.get("ema_slow", 50)),
            ema_fast=signal.ema_fast,
            ema_slow=signal.ema_slow,
            ema_gap_pct=signal.ema_gap_pct,
            rsi_period=int(cfg.get("rsi_period", 14)),
            rsi=signal.rsi,
            rsi_min=float(cfg.get("rsi_min", 45)),
            rsi_max=float(cfg.get("rsi_max", 68)),
            volume=signal.volume,
            avg_volume=signal.avg_volume,
            volume_surge=signal.volume_surge,
            atr=signal.atr,
            atr_pct=atr_pct,
            avg_dollar_volume=signal.avg_dollar_volume,
            reasons="\n".join(f"- {r}" for r in signal.reasons),
        )

        response = requests.post(
            f"{self.base_url}/chat/completions",
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json",
            },
            json={
                "model": self.model,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                "temperature": self.temperature,
                "max_tokens": self.max_tokens,
                "response_format": {"type": "json_object"},
                "stream": False,
            },
            timeout=self.timeout,
        )
        if response.status_code == 429:
            raise RuntimeError("DeepSeek rate limit / insufficient balance (429)")
        response.raise_for_status()
        body = response.json()
        content = body["choices"][0]["message"]["content"]
        return {"content": content, "usage": body.get("usage", {})}

    # -- parsing ----------------------------------------------------------
    def _parse(self, signal, payload: Dict[str, Any]) -> AdvisorReport:
        content = payload.get("content") or ""
        data = _extract_json(content)

        entry = _as_float(data.get("entry"), signal.price) or signal.price
        stop = _as_float(data.get("stop_loss"), 0.0)
        target = _as_float(data.get("target"), 0.0)

        # Guardrails: never let the model return inverted or missing levels.
        if not stop or stop >= entry:
            stop = round(entry - max(1.5 * signal.atr, entry * 0.03), 2)
        if not target:
            risk = entry - stop
            target = round(entry + max(2 * risk, 2 * signal.atr), 2)

        action = str(data.get("action", "WATCH")).upper()
        if action not in {"BUY", "WATCH", "SKIP"}:
            action = "WATCH"

        return AdvisorReport(
            ticker=signal.ticker,
            action=action,
            confidence=min(max(_as_float(data.get("confidence"), 5.0) or 5.0, 0.0), 10.0),
            entry=round(entry, 2),
            stop_loss=round(stop, 2),
            target=round(target, 2),
            rationale=str(data.get("rationale", "")).strip() or "No rationale returned.",
            horizon_days=_as_int(data.get("horizon_days")),
            risk_notes=str(data.get("risk_notes", "")).strip(),
            red_flags=[str(f) for f in (data.get("red_flags") or []) if str(f).strip()],
            model=self.model,
            source="deepseek",
        )

    # -- deterministic fallback ------------------------------------------
    def _rule_based(self, signal, note: str = "") -> AdvisorReport:
        """ATR-anchored plan used when the cloud brain is unavailable."""
        entry = round(signal.price, 2)
        atr = signal.atr or entry * 0.02
        stop = round(entry - 1.5 * atr, 2)
        risk = entry - stop
        target = round(entry + 3 * risk, 2)

        # score 0-10 from the strength of the technical pass
        score = 5.0
        score += min(max(signal.ema_gap_pct, -3), 5) * 0.3
        score += min(max(signal.volume_surge - 1.0, 0), 1.5) * 1.2
        score += 0.8 if 50 <= signal.rsi <= 62 else 0.2
        score = round(min(max(score, 0.0), 10.0), 1)

        return AdvisorReport(
            ticker=signal.ticker,
            action="BUY" if score >= 6.0 else "WATCH",
            confidence=score,
            entry=entry,
            stop_loss=stop,
            target=target,
            horizon_days=10,
            rationale=(
                f"Rule-based plan ({note or 'fallback'}): EMA trend confirmed with "
                f"a {signal.ema_gap_pct:+.2f}% fast/slow gap, RSI {signal.rsi:.1f} in the "
                f"expansion zone and {signal.volume_surge:.2f}x volume participation. "
                "Levels derived from 1.5x ATR risk with a 3:1 reward target."
            ),
            risk_notes=(
                "Invalidated on a daily close below the stop, or if volume dries up "
                "back under the 20-day average."
            ),
            red_flags=["No LLM review performed — fundamentals/news unverified."],
            model=f"{self.model} (skipped)",
            source="rule-based",
            error=note,
        )


def _extract_json(text: str) -> Dict[str, Any]:
    """Parse JSON from a model response, tolerating fences or extra prose."""
    text = (text or "").strip()
    if not text:
        raise ValueError("empty model response")

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    fenced = re.search(r"```(?:json)?\s*(.+?)```", text, re.DOTALL)
    if fenced:
        try:
            return json.loads(fenced.group(1))
        except json.JSONDecodeError:
            pass

    brace = re.search(r"\{.*\}", text, re.DOTALL)
    if brace:
        return json.loads(brace.group(0))

    raise ValueError(f"could not parse JSON from model response: {text[:200]!r}")


def _as_float(value: Any, default: Optional[float]) -> Optional[float]:
    try:
        return float(str(value).replace("$", "").replace(",", "").strip())
    except (TypeError, ValueError):
        return default


def _as_int(value: Any) -> Optional[int]:
    try:
        return int(float(str(value).strip()))
    except (TypeError, ValueError):
        return None
